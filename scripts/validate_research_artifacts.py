"""Validate that reported metrics have backing artifacts."""

from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "validation" / "artifact_crosscheck.md"


def main() -> None:
    findings: list[str] = []

    helmet_csv = ROOT / "docs" / "evaluation" / "violations" / "helmet_reviewed_annotations.csv"
    if helmet_csv.is_file():
        rows = list(csv.DictReader(helmet_csv.open(encoding="utf-8")))
        reviewed = sum(
            1
            for row in rows
            if (row.get("reviewer_label") or "").strip().lower() in ("tp", "fp")
        )
        if reviewed == 0:
            findings.append("WARN: No TP/FP helmet labels — precision not measurable.")
    else:
        findings.append("FAIL: Missing helmet_reviewed_annotations.csv")

    ocr_csv = ROOT / "docs" / "evaluation" / "ocr" / "ocr_review_annotations.csv"
    if ocr_csv.is_file():
        gt = sum(
            1
            for row in csv.DictReader(ocr_csv.open(encoding="utf-8"))
            if (row.get("ground_truth_plate_text") or "").strip()
        )
        if gt == 0:
            findings.append("WARN: OCR ground truth empty — CER NOT MEASURED.")
    else:
        findings.append("WARN: OCR review CSV missing")

    chain = ROOT / "docs" / "research_paper" / "ieee" / "generated" / "chain_latency.json"
    if chain.is_file():
        data = json.loads(chain.read_text(encoding="utf-8"))
        if not data.get("samples"):
            findings.append("WARN: Blockchain latency samples=0 — do not report latency.")

    detector_dirs = sorted((ROOT / "docs" / "evaluation" / "detector").glob("detector_val_test_*"))
    if detector_dirs:
        findings.append(f"OK: Detector experiment dir found ({detector_dirs[-1].name}).")
    else:
        findings.append("WARN: No detector experiment directory under docs/evaluation/detector/")

    lines = ["# Artifact Crosscheck", "", "## Findings", ""]
    lines.extend(f"- {item}" for item in findings)
    lines.append("")
    lines.append("Generated by scripts/validate_research_artifacts.py")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
